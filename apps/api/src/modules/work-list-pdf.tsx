import React from 'react';
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from '@react-pdf/renderer';

export type WorkListModel = {
  trailName: string;
  generatedAt: string;
  maintenanceOwner: string;
  dataSteward: string;
  issues: { title: string; detail: string; owner: string }[];
  workdays: { workDate: string; title: string; host: string; notes: string }[];
  changes: { message: string }[];
  counts: { label: string }[];
};

const styles = StyleSheet.create({
  page: {
    paddingTop: 48,
    paddingHorizontal: 48,
    paddingBottom: 64,
    fontSize: 11,
    fontFamily: 'Helvetica',
    color: '#14233c',
  },
  title: { fontSize: 18, fontFamily: 'Helvetica-Bold', marginBottom: 6 },
  meta: { fontSize: 11, marginBottom: 2, color: '#1b365d' },
  heading: { fontSize: 13, fontFamily: 'Helvetica-Bold', marginTop: 14, marginBottom: 4 },
  item: { marginTop: 8 },
  itemTitle: { fontFamily: 'Helvetica-Bold' },
  body: { marginTop: 2, lineHeight: 1.35 },
  footer: { position: 'absolute', left: 48, right: 48, bottom: 28, fontSize: 8, color: '#5c564c' },
});

function WorkListDocument({ model }: { model: WorkListModel }) {
  return (
    <Document>
      <Page size="LETTER" style={styles.page}>
        <Text style={styles.title}>{model.trailName} work list</Text>
        <Text style={styles.meta}>Generated: {model.generatedAt}</Text>
        <Text style={styles.meta}>Maintenance owner: {model.maintenanceOwner}</Text>
        <Text style={styles.meta}>Data steward: {model.dataSteward}</Text>
        <Text style={styles.heading}>Open problems</Text>
        {model.issues.length === 0 ? <Text>None.</Text> : null}
        {model.issues.map((issue) => (
          <View key={`${issue.title}-${issue.detail}`} style={styles.item}>
            <Text style={styles.itemTitle}>{issue.title}</Text>
            <Text style={styles.body}>{issue.detail}</Text>
            <Text style={styles.body}>Owner: {issue.owner}</Text>
          </View>
        ))}
        <Text style={styles.heading}>Planned work</Text>
        {model.workdays.length === 0 ? <Text>None.</Text> : null}
        {model.workdays.map((day) => (
          <View key={`${day.workDate}-${day.title}`} style={styles.item}>
            <Text style={styles.itemTitle}>
              {day.workDate} — {day.title}
            </Text>
            <Text style={styles.body}>Host: {day.host}</Text>
            {day.notes ? <Text style={styles.body}>{day.notes}</Text> : null}
          </View>
        ))}
        <Text style={styles.heading}>Latest counts</Text>
        {model.counts.length === 0 ? <Text>None.</Text> : null}
        {model.counts.map((count) => (
          <Text key={count.label} style={styles.item}>
            {count.label}
          </Text>
        ))}
        <Text style={styles.heading}>Open map changes</Text>
        {model.changes.length === 0 ? <Text>None.</Text> : null}
        {model.changes.map((change) => (
          <Text key={change.message} style={styles.item}>
            {change.message}
          </Text>
        ))}
        <Text style={styles.footer} fixed>
          Generated by Trail Steward. This list is a snapshot, not a work order.
        </Text>
      </Page>
    </Document>
  );
}

export function renderWorkListPdf(model: WorkListModel): Promise<Buffer> {
  return renderToBuffer(<WorkListDocument model={model} />);
}
