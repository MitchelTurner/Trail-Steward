import React from 'react';
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from '@react-pdf/renderer';

export type PdfModel = {
  title: string;
  community: string | null;
  generatedAt: string;
  answers: { label: string; value: string }[];
  steps: {
    done: boolean;
    title: string;
    howTo: string;
    resources: { title: string; url: string }[];
    contacts: { name: string; websiteUrl: string | null }[];
  }[];
  reviewedRange: string;
};

const styles = StyleSheet.create({
  page: {
    paddingTop: 48,
    paddingHorizontal: 48,
    paddingBottom: 64,
    fontSize: 11,
    fontFamily: 'Helvetica',
    color: '#14233c',
  },
  title: { fontSize: 18, fontFamily: 'Helvetica-Bold', marginBottom: 6 },
  meta: { fontSize: 11, marginBottom: 2, color: '#1b365d' },
  heading: { fontSize: 13, fontFamily: 'Helvetica-Bold', marginTop: 14, marginBottom: 4 },
  step: { marginTop: 10 },
  stepTitle: { fontFamily: 'Helvetica-Bold', fontSize: 12 },
  body: { marginTop: 3, lineHeight: 1.35 },
  item: { marginTop: 2 },
  footer: { position: 'absolute', left: 48, right: 48, bottom: 28, fontSize: 8, color: '#5c564c' },
  pageNumber: { position: 'absolute', right: 48, bottom: 14, fontSize: 8, color: '#5c564c' },
});

function ChecklistDocument({ model }: { model: PdfModel }) {
  return (
    <Document>
      <Page size="LETTER" style={styles.page}>
        <Text style={styles.title}>{model.title}</Text>
        <Text style={styles.meta}>Community: {model.community || 'Not set'}</Text>
        <Text style={styles.meta}>Generated: {model.generatedAt}</Text>
        <Text style={styles.heading}>Your answers</Text>
        {model.answers.map((answer) => (
          <Text key={answer.label} style={styles.item}>
            {answer.label} {answer.value}
          </Text>
        ))}
        <Text style={styles.heading}>Steps</Text>
        {model.steps.map((step) => (
          <View key={step.title} style={styles.step}>
            <Text style={styles.stepTitle}>
              {step.done ? '[x]' : '[ ]'} {step.title}
            </Text>
            <Text style={styles.body}>{step.howTo}</Text>
            {step.resources.map((resource) => (
              <Text key={resource.url} style={styles.item}>
                {resource.title} — {resource.url}
              </Text>
            ))}
            {step.contacts.map((contact) => (
              <Text key={contact.name} style={styles.item}>
                {contact.name}
                {contact.websiteUrl ? ` — ${contact.websiteUrl}` : ''}
              </Text>
            ))}
          </View>
        ))}
        <Text style={styles.footer} fixed>
          Generated by Trail Steward from Southeast Conference's Trail Coordination Guide (draft).
          Content reviewed {model.reviewedRange}.
        </Text>
        <Text
          style={styles.pageNumber}
          fixed
          render={({ pageNumber, totalPages }) => `${pageNumber} / ${totalPages}`}
        />
      </Page>
    </Document>
  );
}

export function renderChecklistPdf(model: PdfModel): Promise<Buffer> {
  return renderToBuffer(<ChecklistDocument model={model} />);
}
